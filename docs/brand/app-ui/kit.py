def app(main, side="sidebar", active="home", mtitle="Home", mback=False, extra_cols="", mright="", palette=None, theme=None, overlay="", tabs=True):
    attrs = (f' data-palette="{palette}"' if palette else "") + (f' data-theme="{theme}"' if theme else "")
    if side == "sidebar":
        s = sidebar(active)
        shell = "ae-shell"
    elif side == "rail":
        s = rail(active)
        shell = "ae-shell ae-shell--rail"
    elif side == "top":
        s = topbar(active)
        shell = "ae-shell ae-shell--top"
    else:
        s = ""
        shell = "ae-shell ae-shell--top"
    cols = ""
    if extra_cols:
        # a context column inside main: grid main
        main = f'<div style="display:grid;grid-template-columns:220px minmax(0,1fr);flex:1;min-height:0" class="ae-ctxwrap">{extra_cols}<div style="min-width:0;display:flex;flex-direction:column">{main}</div></div>'
    tb = tabbar(active if active in ("home", "sites", "tests") else "tests") if tabs else ""
    return (f'<div class="ae-app"{attrs}><div class="{shell}">{s}<main class="ae-main">{mbar(mtitle, mback, mright)}{main}{tb}</main></div>{overlay}</div>')

