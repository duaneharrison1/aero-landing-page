def qr(seed=7):
    # deterministic pseudo QR (drawing only)
    cells = []
    x = seed
    for r in range(21):
        for c in range(21):
            fin = lambda rr, cc: (rr < 7 and cc < 7) or (rr < 7 and cc > 13) or (rr > 13 and cc < 7)
            if fin(r, c):
                rr, cc = r % 14 if r > 13 else r, c % 14 if c > 13 else c
                rr = r - 14 if r > 13 else r; cc = c - 14 if c > 13 else c
                on = rr in (0, 6) or cc in (0, 6) or (2 <= rr <= 4 and 2 <= cc <= 4)
            else:
                x = (x * 1103515245 + 12345) & 0x7fffffff
                on = (x >> 16) % 100 < 46
            cells.append(f'<i class="{"" if on else "o"}"></i>')
    return f'<div class="ae-qr" aria-label="QR code">{"".join(cells)}</div>'

