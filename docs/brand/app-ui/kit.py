def transcript(now_idx=5, playing=True, read=False, notes=True, upto=None, start=0):
    rows = []
    lines = TRANSCRIPT if upto is None else TRANSCRIPT[:upto]
    for k, ln in enumerate(lines):
        if k < start: continue
        t1 = TRANSCRIPT[k+1]["t"] if k+1 < len(TRANSCRIPT) else ln["t"] + 9
        t1 = min(t1, ln["t"] + 9)
        cls = ["ae-tline"]
        if ln.get("fr"): cls.append("is-friction")
        if k == now_idx: cls.append("is-now")
        if ln.get("task"): cls.append("is-task")
        task = f'<div class="ae-tline__task">{E(ln["task"])}</div>' if ln.get("task") else ""
        w = words(ln["txt"], ln["t"], t1)
        if playing and now_idx is not None:
            # mark past/now words for the static frame
            spans = w.split('</span> ')
            if k < now_idx:
                w = w.replace('class="ae-w"', 'class="ae-w is-past"')
            elif k == now_idx:
                parts = w.split('<span class="ae-w"')
                cut = 7
                newparts = [parts[0]]
                for j, p in enumerate(parts[1:]):
                    c = "ae-w is-past" if j < cut else ("ae-w is-now" if j == cut else "ae-w")
                    newparts.append(f'<span class="{c}"' + p)
                w = "".join(newparts)
        note = f'<span class="ae-tline__note">{i("flag","ae-i--sm")} <b>{E(ln["fr"])}</b> · friction point</span>' if (ln.get("fr") and notes) else ""
        rows.append(f'<div class="{" ".join(cls)}" data-t="{ln["t"]*1000}">{task}<span class="ae-tc">{mmss(ln["t"])}</span><span class="ae-tline__text"><span class="ae-tline__words">{w}</span>{note}</span></div>')
    return f'<div class="ae-transcript{" is-playing" if playing else ""}{" ae-transcript--read" if read else ""}">{"".join(rows)}</div>'

