def mmss(s):
    return f"{int(s)//60:02d}:{int(s)%60:02d}"

def words(text, t0, t1):
    """Split a line into word spans with evenly spread example timings (real ones come from the stored word timings)."""
    ws = text.split(" ")
    step = (t1 - t0) / max(len(ws), 1)
    return " ".join(f'<span class="ae-w" data-t="{int((t0 + k*step)*1000)}">{E(w)}</span>' for k, w in enumerate(ws))

