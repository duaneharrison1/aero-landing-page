/* Aero glass button lab, V3 From research: Snell-law squircle refraction, Fresnel-weighted reflection and a key-light specular lip.
   Standalone, no dependencies. Auto-initialises on [data-glass-v3="primary|secondary|dark"] (data-fill="#hex", data-strength="1").
   window.GlassV3(el, opts), GlassV3.refresh(). Global intensity: window.GLASS_INTENSITY (0..3, default 1). Strength: window.GLASS_MODE = 'subtle' | 'liquid'.
   Generated by build.mjs from src/core.js + src/v3.js.
   HOVER LAB COPY (research/web3/glass-lab, 24 Oct 2026). Changes from the source file:
   - no scale on hover or press: the button never moves or changes size, only its light does
   - data-hover="key|lift|shimmer|press|bright|lens" picks a hover; data-press="soft|flat|none" the press
   - a caustic: light through the key-side lip focuses into a soft band inside the opposite lip
   - :focus-visible gets the hover; Enter/Space gets the press; data-force="hover|active" holds a state
   - reduced motion (or window.GLASS_REDUCED): states snap, the light stays at rest, the shimmer stops
   - WEB3 SHARED COPY: adds data-hover="keylift" (key light follows + Lift's deeper bend) and makes it the default
     when data-hover is absent; data-hover="base" turns hover off
   - data-px / data-py (0..1): where the light rests for keyboard focus and held states
   ROUND 5 (web3/glass-r5, 24 Oct 2026 evening):
   - the caustic is back. Round 4 lost it in the sampling: a wash is a stack of radial gradients, and every stop
     of the whole background was averaged into ONE colour (blue + peach + green + white = a near-grey), which
     scored zero as "not colourful" and was then removed again as ambient. Gradients are now read at the point
     each sample lands, pale hues count (in proportion), the hue is lifted to a visible chroma at the glass, and
     the caustic band is tinted by it (it was white, so on white glass it was white on white)
   - slab: a flat face, a short steep bevel and a visible wall of thickness along the bottom, lit by what is near
   - hover "keylift" (the default): key light follows, toned down, plus Lift. Ink glass gets Lift only.
   - .site-nav is frosted glass with a refracting lower edge (see aero.css); buttons in it read the page under it */
