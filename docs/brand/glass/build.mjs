// Builds the four standalone scripts: each is the shared core plus one renderer, in its own IIFE.
import { readFileSync, writeFileSync } from 'node:fs';
const dir = new URL('.', import.meta.url).pathname;
const core = readFileSync(dir + 'src/core.js', 'utf8');
const heads = {
  1: 'V1 Original, tuned: glassEngine.js drawing (body tint, edge glow, bevel, caustic RGB line) fed by environment-aware sources.',
  2: 'V2 Liquid glass, fixed: liquid-glass.js rim lighting with chroma/contrast salience, ambient removal and clamps.',
  3: 'V3 From research: Snell-law squircle refraction, Fresnel-weighted reflection and a key-light specular lip.',
  4: 'V4 Hybrid: the original caustic character on V2 sampling and V3 refraction.',
  5: 'V5 Reference: a port of liquid-glass-react 1.1.1 (MIT, Max Rovensky) at its published defaults.',
};
for (const n of [1, 2, 3, 4, 5]) {
  let body = readFileSync(dir + `src/v${n}.js`, 'utf8');
  if (n === 5) body = body.replace('__MAP__', readFileSync(dir + 'src/v5-map.txt', 'utf8').trim());
  const out = `/* Aero glass button lab, ${heads[n]}\n   Standalone, no dependencies. Auto-initialises on [data-glass-v${n}="primary|secondary|dark"] (data-fill="#hex", data-strength="1").\n   window.GlassV${n}(el, opts), GlassV${n}.refresh(). Global intensity: window.GLASS_INTENSITY (0..3, default 1). Strength: window.GLASS_MODE = 'subtle' | 'liquid'.\n   Generated by build.mjs from src/core.js + src/v${n}.js. */\n(function (W, D) {\n  'use strict';\n  var PFX = 'g${n}', ATTR = 'data-glass-v${n}';\n${core}\n${body}})(window, document);\n`;
  writeFileSync(dir + `glass-v${n}.js`, out);
}
console.log('built');
